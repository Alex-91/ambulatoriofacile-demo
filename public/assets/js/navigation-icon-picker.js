/* Local Font Awesome catalog; previews fetch only bundled SVG assets. */
'use strict';
window.createNavigationIconPicker = function ({catalog, legacy, assetBase, onSelect}) {
    const byId = new Map(catalog.map(item => [item.id, item]));
    const $ = id => document.getElementById(id);
    const dialog = $('icon-dialog'), pageSize = 72;
    let page = 0, selected = '';
    const families = {menu: 'Menu attuale', solid: 'Solid', regular: 'Regular', brands: 'Brands'};
    const translations = {calendario:'calendar',utente:'user',utenti:'users',paziente:'user',pazienti:'users',medico:'user doctor',esame:'microscope',esami:'microscope',cuore:'heart',casa:'house',impostazioni:'gear',ingranaggio:'gear',cartella:'folder',documento:'file',fattura:'file invoice',messaggio:'message',posta:'envelope',telefono:'phone',ospedale:'hospital',stetoscopio:'stethoscope',ricerca:'magnifying glass',cerca:'magnifying glass',lente:'magnifying glass',grafico:'chart',soldi:'money',euro:'euro',orologio:'clock',notifica:'bell',notifiche:'bell',campanella:'bell',lucchetto:'lock',stampante:'print',stampa:'print',foto:'image',immagine:'image',immagini:'images',freccia:'arrow',freccie:'arrows',frecce:'arrows',occhio:'eye',chiave:'key',salva:'floppy disk',cestino:'trash',scarica:'download',carica:'upload',lista:'list',gruppo:'users',gruppi:'users',edificio:'building',scudo:'shield',aiuto:'circle question',uscita:'right from bracket'};
    const normalize = text => text.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[-_:]/g,' ').trim();
    function icon(id) {
        if (legacy[id]) {
            const span = document.createElement('span');
            span.innerHTML = legacy[id]; // Trusted SVGs generated by the server, never user input.
            return span.firstElementChild;
        }
        const item = byId.get(id), img = document.createElement('img');
        img.alt = ''; img.className = 'af-menu-icon'; img.width = 22; img.height = 22;
        if (item?.asset) img.src = assetBase + item.asset;
        return img;
    }
    function filtered() {
        const query = normalize($('icon-search').value), family = $('icon-family').value;
        const translated = translations[query] || query;
        const tokens = translated.split(/\s+/).filter(Boolean);
        return catalog.filter(item => (!family || item.family === family) && (
            normalize(item.label).includes(query) || tokens.every(token => normalize(item.label).includes(token))
        ));
    }
    function render() {
        const items = filtered(), pages = Math.max(1, Math.ceil(items.length / pageSize));
        page = Math.min(page, pages - 1);
        $('icon-results').replaceChildren();
        for (const item of items.slice(page * pageSize, (page + 1) * pageSize)) {
            const button = document.createElement('button');
            button.type = 'button'; button.className = 'icon-choice'; button.dataset.icon = item.id;
            button.setAttribute('aria-label', item.label + ' · ' + families[item.family]);
            button.setAttribute('aria-pressed', String(item.id === selected));
            button.title = item.label + ' · ' + families[item.family];
            const label = document.createElement('span'); label.textContent = item.label;
            const family = document.createElement('small'); family.textContent = families[item.family];
            button.append(icon(item.id), label, family);
            button.onclick = () => { selected = item.id; dialog.close(); onSelect(item.id); };
            $('icon-results').append(button);
        }
        $('icon-count').textContent = `${items.length} icone · pagina ${page + 1} di ${pages}`;
        $('icon-no-results').hidden = items.length > 0;
        $('icon-prev').disabled = page === 0;
        $('icon-next').disabled = page === pages - 1;
        $('icon-results').scrollTop = 0;
    }
    $('choose-icon').onclick = () => {
        page = 0; $('icon-search').value = ''; $('icon-family').value = '';
        render(); dialog.showModal(); $('icon-search').focus();
    };
    $('icon-close').onclick = () => dialog.close();
    dialog.addEventListener('keydown', event => {
        if(event.key === 'Escape') { event.preventDefault(); dialog.close(); }
    });
    $('icon-search').oninput = $('icon-family').onchange = () => { page = 0; render(); };
    $('icon-prev').onclick = () => { page--; render(); };
    $('icon-next').onclick = () => { page++; render(); };
    dialog.addEventListener('click', event => { if(event.target === dialog) dialog.close(); });
    return {
        icon,
        setSelection(id) {
            selected = id;
            const item = byId.get(id), label = item ? `${item.label} · ${families[item.family]}` : id;
            $('choose-icon').replaceChildren(icon(id), document.createTextNode(label), document.createTextNode(' — Cambia'));
        }
    };
};
